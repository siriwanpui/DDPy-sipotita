#!/usr/bin/env python3

original_array = [2, 8, 9, 48, 8, 22, -12, 2]       # 1. กำหนดอาร์เรย์เริ่มต้น (Original Array) โดยใช้โครงสร้างข้อมูลแบบ List

new_array = []                                      # 2. สร้างอาร์เรย์ใหม่ที่เป็นลิสต์ว่าง (Empty List) เอาไว้รอเก็บผลลัพธ์

for number in original_array:                       # 3. ใช้ Loop (for) วนลูปดึงข้อมูลจากอาร์เรย์เดิมมาบวก 2 ทีละตัว
    new_array.append(number + 2)                    # นำตัวเลขปัจจุบันมาบวก 2 แล้วเพิ่มเข้าไปในลิสต์ใหม่ด้วยคำสั่ง .append()

print(f"Original array: {original_array}")          # 4. แสดงผลลัพธ์อาร์เรย์ทั้งสองตัวออกทางหน้าจอตามรูปแบบที่โจทย์กำหนด
print(f"New array: {new_array}")








