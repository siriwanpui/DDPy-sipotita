#!/usr/bin/env python3

original_array = [2, 8, 9, 48, 8, 22, -12, 2]     # 1. กำหนดอาร์เรย์เริ่มต้น (Original Array)

new_array = []                                    # 2. สร้างอาร์เรย์ใหม่ที่เป็นลิสต์ว่างไว้รอเก็บผลลัพธ์

for number in original_array:                     # 3. วนลูปตรวจสอบข้อมูลทีละตัว
    if number > 5:                                # เพิ่มเงื่อนไข (if): ตรวจสอบว่าตัวเลขปัจจุบัน "มากกว่า 5" หรือไม่
        new_array.append(number + 2)              # ถ้ามากกว่า 5 ให้นำมาบวก 2 แล้วเพิ่มเข้าไปในลิสต์ใหม่

print(original_array)                             # 4. แสดงผลลัพธ์ตามรูปแบบที่โจทย์ระบุ (แสดงเฉพาะตัวอาเรย์โดยไม่มีข้อความนำหน้า)
print(new_array)





