#!/usr/bin/env python3
import sys


class StringModifier:                           # 1. สร้าง Class เพื่อเป็นโครงสร้างหลักของโปรแกรม
    
    def shrink(self, text_string):              # 2. Method แท้ตัวที่ 1: ตัดข้อความ (รับ self เป็นพารามิเตอร์ตัวแรก)
        result = text_string[:8]
        print(result)

    def enlarge(self, text_string):             # 3. Method แท้ตัวที่ 2: ขยายข้อความ (รับ self เป็นพารามิเตอร์ตัวแรก)
        needed_z = 8 - len(text_string)
        result = text_string + ('Z' * needed_z)
        print(result)

# -------------------------------------------------------------
# --- ส่วนควบคุมหลักของโปรแกรม (Main Logic) ---

arguments = sys.argv[1:]            # ดึงพารามิเตอร์จาก Terminal

modifier = StringModifier()         # สร้างอ็อบเจกต์ขึ้นมาจากคลาส เพื่อเรียกใช้งาน Method แท้

if len(arguments) < 1:              # เงื่อนไขการตรวจสอบตามโจทย์
    print("none")
else:
    for arg in arguments:
        if len(arg) > 8:
            modifier.shrink(arg)    # เรียกใช้ Method แท้ผ่านอ็อบเจกต์
        elif len(arg) < 8:
            modifier.enlarge(arg)   # เรียกใช้ Method แท้ผ่านอ็อบเจกต์
        else:
            print(arg)








