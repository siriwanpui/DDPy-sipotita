#!/usr/bin/env python3

import sys

def downcase_it(text_string):                   # 1. นิยามฟังก์ชันตามที่โจทย์กำหนด
    return text_string.lower()                  # ใช้ Method สำเร็จรูป .lower() เพื่อแปลงเป็นตัวพิมพ์เล็กทั้งหมด

                                                # 2. ส่วนดึงข้อมูลพารามิเตอร์จาก Terminal
arguments = sys.argv[1:]                        # sys.argv[1:] คือการตัดเอาเฉพาะข้อความที่พิมพ์ต่อท้ายชื่อไฟล์มาทำเป็น List

if not arguments:                               # 3. เช็คเงื่อนไขตามตัวอย่างโจทย์
    print("none")                               # ถ้าไม่มีพารามิเตอร์ส่งมาเลย ให้พิมพ์ "none"
else:
    for arg in arguments:                       # ถ้ามีพารามิเตอร์ส่งมา ให้วนลูปนำแต่ละข้อความไปแปลงและพิมพ์ออกมา
        print(downcase_it(arg))













