#!/usr/bin/env python3

def array_of_names(persons_dict):

    full_names_list = []                            # 1. สร้าง List ว่างสำหรับเก็บผลลัพธ์
    

    for first, last in persons_dict.items():        # 2. ใช้ Loop ดึงข้อมูล First Name (key) และ Last Name (value) ออกมาคู่กัน
        clean_first = first.capitalize()            # 3. แปลงตัวอักษรตัวแรกให้เป็นตัวพิมพ์ใหญ่ด้วย .capitalize()
        clean_last = last.capitalize()
        
        full_name = f"{clean_first} {clean_last}"   # 4. นำชื่อและนามสกุลมาต่อกันด้วยช่องว่าง
        
        full_names_list.append(full_name)           # 5. เพิ่มชื่อเต็มเข้าไปใน List ผลลัพธ์
        
    return full_names_list                          # 6. ส่ง List ผลลัพธ์กลับออกไป

persons = {                                         # --- ส่วนทดสอบโค้ดตามตัวอย่างในโจทย์ ---
    "jean": "valjean",
    "grace": "hopper",
    "xavier": "niel",
    "fifi": "brindacier"
}

print(array_of_names(persons))                      # เรียกใช้งานฟังก์ชันและพิมพ์ผลลัพธ์









