#!/usr/bin/env python3

# รับอินพุตจากผู้ใช้ และแปลงจากตัวหนังสือให้เป็นตัวเลขทศนิยม (Float) ทันที
num = float(input("Give me a number: "))

# ตรวจสอบว่าตัวเลขนี้มีค่าเท่ากับจำนวนเต็มของตัวมันเองหรือไม่
if num == int(num):
    print("This number is an integer.")
else:
    print("This number is a decimal.")






