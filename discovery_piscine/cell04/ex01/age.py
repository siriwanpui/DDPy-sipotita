#!/usr/bin/env python3

age_string = input("Please tell me your age: ")     # รับอินพุตอายุจากผู้ใช้ และแปลงจากตัวหนังสือ (String) ให้กลายเป็นตัวเลข (Integer)
age = int(age_string)

print(f"You are currently {age} years old.")        # แสดงอายุปัจจุบัน

print(f"In 10 years, you'll be {age + 10} years old.")      # คำนวณและแสดงอายุในอีก 10, 20 และ 30 ปีข้างหน้า
print(f"In 20 years, you'll be {age + 20} years old.")
print(f"In 30 years, you'll be {age + 30} years old.")






